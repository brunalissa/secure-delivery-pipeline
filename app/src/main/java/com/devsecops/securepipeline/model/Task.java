package com.devsecops.securepipeline.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import java.time.LocalDateTime;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * ───────────────────────────────────────────────────────────────────────────── Task — JPA Entity
 * (Domain Model) ─────────────────────────────────────────────────────────────────────────────
 *
 * <p>Represents a "Task" in a simple task-management system. This entity demonstrates:
 *
 * <ul>
 *   <li>JPA/Hibernate ORM mapping annotations
 *   <li>Bean Validation constraints (applied at the entity AND DTO level)
 *   <li>Audit fields: createdAt / updatedAt (auto-populated by Hibernate)
 *   <li>Lombok for boilerplate removal (getters/setters/etc.)
 * </ul>
 *
 * <p><b>Table strategy:</b> {@link GenerationType#IDENTITY} uses database auto-increment, which is
 * the PostgreSQL default for SERIAL columns.
 *
 * <p><b>Note on dual validation:</b> We also validate at the DTO layer ({@link
 * com.devsecops.securepipeline.dto.TaskCreateDto}) because the entity should not be directly
 * exposed via the REST API. This is a REST best practice that prevents over-posting and
 * mass-assignment vulnerabilities.
 *
 * @author DevSecOps Team
 * @version 1.0.0
 * @since 1.0.0 ─────────────────────────────────────────────────────────────────────────────
 */
@Entity
@Table(name = "tasks")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Task {

  /**
   * Primary key. Auto-generated by the database (SERIAL / IDENTITY). Null until persisted; the
   * {@code @Id} annotation marks this as the entity identifier.
   */
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  /**
   * Task title. Required, must be between 3 and 100 characters. Bean Validation annotation ensures
   * this is never empty or too short.
   */
  @NotBlank(message = "Title is required")
  @Size(min = 3, max = 100, message = "Title must be between 3 and 100 characters")
  @Column(nullable = false, length = 100)
  private String title;

  /**
   * Task description. Optional, max 500 characters. Demonstrates nullable column with a length
   * constraint.
   */
  @Size(max = 500, message = "Description must not exceed 500 characters")
  @Column(length = 500)
  private String description;

  /**
   * Enum for task status: PENDING, IN_PROGRESS, COMPLETED. Stored as a VARCHAR(20) in the database
   * by default.
   */
  @Enumerated(EnumType.STRING)
  @Column(nullable = false, length = 20)
  private TaskStatus status;

  /**
   * Task priority: LOW, MEDIUM, HIGH, CRITICAL. Uses the same EnumType.STRING strategy for
   * readability.
   */
  @Enumerated(EnumType.STRING)
  @Column(nullable = false, length = 20)
  private TaskPriority priority;

  /**
   * Timestamp when the task was created. Automatically set by Hibernate on insert. {@link
   * CreationTimestamp} ensures this is never null after persist.
   */
  @CreationTimestamp
  @Column(name = "created_at", nullable = false, updatable = false)
  private LocalDateTime createdAt;

  /**
   * Timestamp when the task was last modified. Updated automatically on every update. {@link
   * UpdateTimestamp} ensures this is always current.
   */
  @UpdateTimestamp
  @Column(name = "updated_at", nullable = false)
  private LocalDateTime updatedAt;
}
